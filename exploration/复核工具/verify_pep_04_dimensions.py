def psat(Tc):
    # IAPWS 简化（Buck 1996）
    return 0.61121 * np.exp((18.678 - Tc / 234.5) * Tc / (257.14 + Tc)) * 1000.0  # Pa
def pv_from_w(w, p=101325.0):
    return p * w / (0.621945 + w)
for Tc, w in ((28.0, 0.01963), (50.0, 0.050908)):
    pv = pv_from_w(w)
    print('   T=%.0f°C, w=%.4f kg/kg: pv=%.3f kPa, psat=%.3f kPa, RH=%.1f%%'
          % (Tc, w, pv / 1000, psat(Tc) / 1000, pv / psat(Tc) * 100))
